const hoursFromNow = (h) => new Date(Date.now() + h * 3600 * 1000).toISOString();
const daysAgo = (d) => new Date(Date.now() - d * 24 * 3600 * 1000).toISOString();

// Builds a realistic 30-day price trail: it starts near `originalPrice`
// (or the deal price, if there's no original to compare against) and
// declines toward the current `dealPrice`, with small day-to-day jitter —
// so the scoring engine's 30/90-day average comparison reflects a genuine
// discount rather than averaging a flat line at the already-discounted price.
function history(originalPrice, dealPrice, days) {
  const start = originalPrice ?? dealPrice;
  const arr = [];
  for (let i = days; i >= 0; i -= 3) {
    const t = i / days;
    const base = dealPrice + (start - dealPrice) * t;
    const jitter = 1 + Math.sin(i) * 0.03;
    arr.push({ price: Math.max(0, Math.round(base * jitter)), date: daysAgo(i) });
  }
  return arr;
}

