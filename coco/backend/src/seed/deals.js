function seedDeals() {
  return RAW.map((d, i) => {
    const dealPrice = d.dealPrice;
    const savingsPercent =
      d.originalPrice && dealPrice != null && d.originalPrice > 0
        ? Math.round(((d.originalPrice - dealPrice) / d.originalPrice) * 100)
        : null;
    return {
      id: `d${i + 1}`,
      brand: d.brand,
      brandLogo: d.brandLogo,
      title: d.title,
      description: d.description,
      category: d.category,
      sourceCategory: null, // not produced by a Part 1 source — legacy seed data
      sourceId: null,
      imageUrl: d.imageUrl,
      dealUrl: d.dealUrl,
      originalPrice: d.originalPrice,
      dealPrice: d.dealPrice,
      savingsPercent,
      expiryDate: hoursFromNow(d.expiryHours),
      createdAt: daysAgo(d.createdDaysAgo),
      qualityScore: 50,
      priceHistory: dealPrice != null ? history(d.originalPrice, dealPrice, 30) : [],
      upvotes: d.upvotes,
      downvotes: d.downvotes,
      stillWorksCount: d.stillWorksCount,
      expiredCount: d.expiredCount,
      isVerified: d.stillWorksCount >= 10,
    };
  });
}

